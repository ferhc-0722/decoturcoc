create table if not exists productos (
  id serial primary key,
  codigo text not null,
  color text not null,
  precio_min numeric(10,2) not null default 0,
  precio_max numeric(10,2) not null default 0,
  stock int not null default 0,
  estado text not null default 'disponible' check (estado in ('disponible','agotado')),
  foto_url text,
  actualizado timestamptz default now(),
  unique (codigo, color)
);
create table if not exists medidas (id serial primary key, medida text unique not null);
create table if not exists producto_medidas (
  producto_id int references productos(id) on delete cascade,
  medida_id int references medidas(id) on delete cascade,
  precio numeric(10,2),
  stock int not null default 0,
  primary key (producto_id, medida_id)
);
create table if not exists historial_precios (
  id serial primary key,
  producto_id int references productos(id) on delete cascade,
  precio_min numeric(10,2),
  precio_max numeric(10,2),
  cambiado timestamptz default now()
);
create table if not exists movimientos (
  id serial primary key,
  fecha date not null default current_date,
  tipo text not null check (tipo in ('venta','compra','gasto','ingreso')),
  categoria text,
  descripcion text,
  monto numeric(10,2) not null default 0,
  producto_id int references productos(id) on delete set null,
  cantidad int not null default 0
);

